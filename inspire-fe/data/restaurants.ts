// Helper function to format hours
function formatHours(hours: string): string {
  const [open, close] = hours.split("-");
  return `Mở cửa ${open} - ${close}`;
}

// Helper function to generate description
function generateDescription(name: string, cuisine: string): string {
  const lowerName = name.toLowerCase();
  if (lowerName.includes("phở")) {
    return "Quán phở truyền thống với nước dùng đậm đà, thịt tươi ngon. Không gian ấm cúng, phù hợp cho bữa sáng và bữa trưa.";
  }
  if (lowerName.includes("bún")) {
    return "Quán bún nổi tiếng với hương vị đặc trưng miền Bắc. Nguyên liệu tươi ngon, giá cả hợp lý.";
  }
  if (lowerName.includes("lẩu")) {
    return "Nhà hàng lẩu với nhiều loại lẩu đa dạng. Không gian rộng rãi, phù hợp cho nhóm đông người.";
  }
  if (lowerName.includes("buffet")) {
    return "Buffet tự chọn với nhiều món ăn đa dạng. Giá cả hợp lý, phù hợp cho gia đình và bạn bè.";
  }
  if (lowerName.includes("cơm")) {
    return "Quán cơm văn phòng với các món ăn nhanh, tiện lợi. Phục vụ nhanh chóng, giá cả phải chăng.";
  }
  return `Nhà hàng ${cuisine} với hương vị đặc trưng. Không gian thoải mái, phục vụ tận tình.`;
}


